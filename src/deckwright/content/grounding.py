# Сокращённые множители: без числа перед ними это единица, а не число.
_ABBREVIATED = frozenset({"тыс", "млн", "млрд", "трлн"})
_WORD = re.compile(r"\d+(?:[.,]\d+)?|[а-яё]+|\S", re.IGNORECASE)


def word_numbers(text: str) -> set[float]:
    """Числа, записанные словами: «четыре», «пяти тысяч», «двести сорок».

    Подряд идущие числительные складываются в одно число; множитель
    («тысяч», «млн») умножает накопленное. Множитель без числительного —
    «тысячи клиентов» — это тысяча. Множитель сразу после цифр («412 тыс.»)
    — масштаб записи числа, а не отдельное число: его учитывает
    `is_grounded`.
    """
    found: set[float] = set()
    total = group = 0.0
    seen = False
    digits = False
    for token in _WORD.findall(text.lower()):
        after_digits, digits = digits, token[0].isdigit()
        if token in _UNITS:
            group += _UNITS[token]
            seen = True
        elif token in _MULTIPLIERS and after_digits and not seen:
            continue
        elif token in _ABBREVIATED and not seen:
            # «млн» без числа — единица измерения («Выручка (млн руб.)»), а
            # не миллион: иначе аудит находил на слайде «1e+06», которого во
            # входе нет. Полное слово без числа («тысячи клиентов») — число.
            continue
        elif token in _MULTIPLIERS:
            total += (group or 1) * _MULTIPLIERS[token]
            group = 0.0
            seen = True
        else:
            if seen:
                found.add(total + group)
            total = group = 0.0
            seen = False
    if seen:
        found.add(total + group)
    return found


def source_numbers(text: str) -> set[float]:
    """Все числа текста документа — цифрами и словами."""
    found: set[float] = set()
    for match in _NUMBER.findall(text):
        cleaned = re.sub(r"[   ]", "", match).replace(",", ".")
        try:
            found.add(float(cleaned))
        except ValueError:
            continue
    return found | word_numbers(text)


def is_grounded(value: float, numbers: set[float]) -> bool:
    """Есть ли число во входе — как есть или в другом масштабе записи.

    Знак не читается, и это не поблажка. Числа входа собирает
    `source_numbers`, а её выражение начинается с цифры: «−6» из таблицы
    приходит сюда как `6`, и любое отрицательное значение не сошлось бы
    ни с чем. На живом отчёте о продажах так и вышло: факт «корпоративные
    заказы снизились на 6 %» модель вернула со значением −6, и настоящее
    число из таблицы было выброшено как выдуманное. Хуже того, ряд
    отбрасывается целиком из-за одной своей точки — колонка динамики
    «+8 / +41 / −6» уносила с собой весь график.

    Направление несёт текст («снизились на 6 %»), а не знак числа, и
    сверка чисел `plan/figures.py` знак тоже не читает. Выдумку это не
    пропускает: 7 при 6 во входе не сходится и здесь.
    """
    if value == 0:
        return 0.0 in numbers
    for scale in _SCALES:
        target = abs(value) * scale
        for number in numbers:
            if number and abs(abs(number) - target) <= target * TOLERANCE:
                return True
    return False


def ungrounded(text: str, numbers: set[float], small: int = 0) -> list[float]:
    """Числа строки, которых во входе нет.

    `small` — целые до этого значения считаются счётом, а не фактом: «три
    шага», нумерация этапов, «2 варианта». Их проверять не с чем.
    """
    return [
        value
        for value in sorted(source_numbers(text))
        if not (value.is_integer() and 0 <= value <= small) and not is_grounded(value, numbers)
    ]


def normalize(text: str) -> str:
    """Текст для поиска цитаты: без различий в пробелах, кавычках и регистре."""
    text = text.lower().replace("ё", "е")
    text = re.sub(r"[«»\"'“”„]", "", text)
    return re.sub(r"\s+", " ", text).strip()
